export function getDashboardStats() {
  const activeProjects = MOCK_PROJECTS.filter((p) => p.status === "IN_EXECUTION").length;
  const totalBudget = MOCK_PROJECTS.reduce((sum, p) => sum + p.totalBudget, 0);
  const totalExecuted = MOCK_PROJECTS.reduce((sum, p) => sum + p.executedAmount, 0);
  const pendingCuts = MOCK_WORK_CUTS.filter((c) => ["SUBMITTED", "VALIDATED"].includes(c.status)).length;
  const pendingPayments = MOCK_PAYMENTS.filter((p) => ["PENDING", "APPROVED_LEVEL_1", "APPROVED_LEVEL_2"].includes(p.status)).length;
  const activeClients = MOCK_CLIENTS.filter((c) => c.status === "WON").length;
  const openQuotations = MOCK_QUOTATIONS.filter((q) => ["SENT", "VIEWED", "DRAFT"].includes(q.status)).length;

  return {
    activeProjects,
    totalBudget,
    totalExecuted,
    executionPercent: totalBudget > 0 ? (totalExecuted / totalBudget) * 100 : 0,
    pendingCuts,
    pendingPayments,
    activeClients,
    openQuotations,
  };
}

